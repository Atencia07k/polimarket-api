-- Seguridad: usuarios de la API y refresh tokens rotativos (solo se guarda el hash SHA-256 del token).

CREATE TABLE usuario (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    username       VARCHAR(50)              NOT NULL,
    password_hash  VARCHAR(255)             NOT NULL,
    rol            VARCHAR(20)              NOT NULL,
    activo         BOOLEAN                  NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT usuario_pkey PRIMARY KEY (id),
    CONSTRAINT uk_usuario_username UNIQUE (username),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMIN', 'VENDEDOR'))
);

CREATE TABLE refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id INTEGER                  NOT NULL,
    token_hash VARCHAR(64)              NOT NULL,
    familia    UUID                     NOT NULL,
    expira_en  TIMESTAMP WITH TIME ZONE NOT NULL,
    revocado   BOOLEAN                  NOT NULL,
    creado_en  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT refresh_token_pkey PRIMARY KEY (id),
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE INDEX ix_refresh_token_usuario ON refresh_token (usuario_id);
CREATE INDEX ix_refresh_token_familia ON refresh_token (familia);
