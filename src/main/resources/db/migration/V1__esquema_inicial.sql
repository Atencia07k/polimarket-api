-- PoliMarket: esquema inicial de los componentes de negocio (14 tablas).
-- Equivale al esquema que generaba Hibernate a partir de las entidades JPA.

CREATE TABLE vendedor (
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    CONSTRAINT vendedor_pkey PRIMARY KEY (id)
);

CREATE TABLE autorizacion_rrhh (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    estado      VARCHAR(255) NOT NULL,
    fecha       DATE         NOT NULL,
    vendedor_id INTEGER      NOT NULL,
    CONSTRAINT autorizacion_rrhh_pkey PRIMARY KEY (id),
    CONSTRAINT fk_autorizacion_rrhh_vendedor FOREIGN KEY (vendedor_id) REFERENCES vendedor (id)
);

CREATE TABLE cliente (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    direccion VARCHAR(255) NOT NULL,
    nombre    VARCHAR(255) NOT NULL,
    CONSTRAINT cliente_pkey PRIMARY KEY (id)
);

CREATE TABLE proveedor (
    nit      VARCHAR(255) NOT NULL,
    contacto VARCHAR(255) NOT NULL,
    nombre   VARCHAR(255) NOT NULL,
    CONSTRAINT proveedor_pkey PRIMARY KEY (nit)
);

CREATE TABLE producto (
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255)     NOT NULL,
    precio DOUBLE PRECISION NOT NULL,
    CONSTRAINT producto_pkey PRIMARY KEY (id)
);

CREATE TABLE producto_proveedor (
    producto_id   INTEGER      NOT NULL,
    proveedor_nit VARCHAR(255) NOT NULL,
    CONSTRAINT producto_proveedor_pkey PRIMARY KEY (producto_id, proveedor_nit),
    CONSTRAINT fk_producto_proveedor_producto FOREIGN KEY (producto_id) REFERENCES producto (id),
    CONSTRAINT fk_producto_proveedor_proveedor FOREIGN KEY (proveedor_nit) REFERENCES proveedor (nit)
);

CREATE TABLE bodega (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ubicacion VARCHAR(255) NOT NULL,
    CONSTRAINT bodega_pkey PRIMARY KEY (id)
);

CREATE TABLE inventario (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    stock        INTEGER NOT NULL,
    stock_minimo INTEGER NOT NULL,
    bodega_id    INTEGER NOT NULL,
    producto_id  INTEGER NOT NULL,
    CONSTRAINT inventario_pkey PRIMARY KEY (id),
    CONSTRAINT uk_inventario_bodega_producto UNIQUE (bodega_id, producto_id),
    CONSTRAINT fk_inventario_bodega FOREIGN KEY (bodega_id) REFERENCES bodega (id),
    CONSTRAINT fk_inventario_producto FOREIGN KEY (producto_id) REFERENCES producto (id)
);

CREATE TABLE venta (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    estado      VARCHAR(255)     NOT NULL,
    fecha       DATE             NOT NULL,
    total       DOUBLE PRECISION NOT NULL,
    cliente_id  INTEGER          NOT NULL,
    vendedor_id INTEGER          NOT NULL,
    CONSTRAINT venta_pkey PRIMARY KEY (id),
    CONSTRAINT fk_venta_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    CONSTRAINT fk_venta_vendedor FOREIGN KEY (vendedor_id) REFERENCES vendedor (id)
);

CREATE TABLE detalle_venta (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cantidad    INTEGER          NOT NULL,
    precio      DOUBLE PRECISION NOT NULL,
    producto_id INTEGER          NOT NULL,
    venta_id    INTEGER          NOT NULL,
    CONSTRAINT detalle_venta_pkey PRIMARY KEY (id),
    CONSTRAINT fk_detalle_venta_producto FOREIGN KEY (producto_id) REFERENCES producto (id),
    CONSTRAINT fk_detalle_venta_venta FOREIGN KEY (venta_id) REFERENCES venta (id)
);

CREATE TABLE entrega (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    direccion VARCHAR(255) NOT NULL,
    estado    VARCHAR(255) NOT NULL,
    fecha     DATE         NOT NULL,
    venta_id  INTEGER      NOT NULL,
    CONSTRAINT entrega_pkey PRIMARY KEY (id),
    CONSTRAINT uk_entrega_venta UNIQUE (venta_id),
    CONSTRAINT fk_entrega_venta FOREIGN KEY (venta_id) REFERENCES venta (id)
);

CREATE TABLE compra_proveedor (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    estado        VARCHAR(255) NOT NULL,
    fecha         DATE         NOT NULL,
    proveedor_nit VARCHAR(255) NOT NULL,
    CONSTRAINT compra_proveedor_pkey PRIMARY KEY (id),
    CONSTRAINT fk_compra_proveedor_proveedor FOREIGN KEY (proveedor_nit) REFERENCES proveedor (nit)
);

CREATE TABLE detalle_compra (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cantidad            INTEGER          NOT NULL,
    precio              DOUBLE PRECISION NOT NULL,
    compra_proveedor_id INTEGER          NOT NULL,
    producto_id         INTEGER          NOT NULL,
    CONSTRAINT detalle_compra_pkey PRIMARY KEY (id),
    CONSTRAINT fk_detalle_compra_compra_proveedor FOREIGN KEY (compra_proveedor_id) REFERENCES compra_proveedor (id),
    CONSTRAINT fk_detalle_compra_producto FOREIGN KEY (producto_id) REFERENCES producto (id)
);

CREATE TABLE movimiento_stock (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cantidad            INTEGER      NOT NULL,
    fecha               DATE         NOT NULL,
    tipo                VARCHAR(255) NOT NULL,
    compra_proveedor_id INTEGER,
    entrega_id          INTEGER,
    inventario_id       INTEGER      NOT NULL,
    CONSTRAINT movimiento_stock_pkey PRIMARY KEY (id),
    CONSTRAINT ck_movimiento_stock_tipo CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT ck_movimiento_stock_origen CHECK ((compra_proveedor_id IS NULL OR tipo = 'ENTRADA')
        AND (entrega_id IS NULL OR tipo = 'SALIDA')),
    CONSTRAINT fk_movimiento_stock_compra_proveedor FOREIGN KEY (compra_proveedor_id) REFERENCES compra_proveedor (id),
    CONSTRAINT fk_movimiento_stock_entrega FOREIGN KEY (entrega_id) REFERENCES entrega (id),
    CONSTRAINT fk_movimiento_stock_inventario FOREIGN KEY (inventario_id) REFERENCES inventario (id)
);
